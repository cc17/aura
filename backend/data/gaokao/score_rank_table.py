def get_rank_for_score(
    province: str, year: int, subject_type: str, score: int
) -> int | None:
    """Look up the provincial rank for a given score using linear interpolation.

    Returns None if the province/year/subject_type combination is not found
    or the score is out of the table range.
    """
    table = _TABLES.get((province, year, subject_type))
    if table is None:
        return None

    # Table is sorted descending by score
    max_score = table[0][0]
    min_score = table[-1][0]

    if score > max_score:
        return 1  # Above highest recorded score
    if score < min_score:
        return None  # Below lowest recorded score

    # Find the two bracketing entries for interpolation
    for i in range(len(table) - 1):
        high_score, high_rank = table[i]
        low_score, low_rank = table[i + 1]

        if low_score <= score <= high_score:
            if high_score == low_score:
                return high_rank
            # Linear interpolation: higher score → lower rank (better)
            fraction = (high_score - score) / (high_score - low_score)
            return round(high_rank + fraction * (low_rank - high_rank))

    return None


def get_score_for_rank(
    province: str, year: int, subject_type: str, rank: int
) -> int | None:
    """Reverse lookup: given a rank, find the corresponding score.

    Returns None if the province/year/subject_type combination is not found
    or the rank is out of the table range.
    """
    table = _TABLES.get((province, year, subject_type))
    if table is None:
        return None

    min_rank = table[0][1]  # Rank at highest score
    max_rank = table[-1][1]  # Rank at lowest score

    if rank < min_rank:
        return table[0][0]  # Better than best recorded
    if rank > max_rank:
        return None  # Worse than lowest recorded

    # Find the two bracketing entries (table sorted: score desc, rank asc)
    for i in range(len(table) - 1):
        high_score, high_rank = table[i]
        low_score, low_rank = table[i + 1]

        if high_rank <= rank <= low_rank:
            if low_rank == high_rank:
                return high_score
            fraction = (rank - high_rank) / (low_rank - high_rank)
            return round(high_score - fraction * (high_score - low_score))

    return None
